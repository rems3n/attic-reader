@pytest.mark.parametrize("principal, m_sg, m_pl, f_sg, f_pl, n_pl", GOLD, ids=[g[0][0] for g in GOLD])
def test_participle_gold(principal, m_sg, m_pl, f_sg, f_pl, n_pl):
    rows = decline_participle(*principal)
    assert " ".join(rows[("m", "sg")]) == m_sg
    assert " ".join(rows[("m", "pl")]) == m_pl
    assert " ".join(rows[("f", "sg")]) == f_sg
    assert " ".join(rows[("f", "pl")]) == f_pl
    assert " ".join(rows[("n", "pl")]) == n_pl


def _entry(lemma):
    return next(e for e in data.all_entries() if e["lemma"] == lemma)


@pytest.mark.parametrize("lemma, cell, form", [
    ("λύω", "aorist.active.participle.gen.pl.f", "λυσασῶν"),
    ("λύω", "present.middle/passive.participle.dat.sg.f", "λυομένῃ"),
    ("λύω", "aorist.passive.participle.gen.sg.m", "λυθέντος"),
    ("λαμβάνω", "aorist.active.participle.gen.sg.m", "λαβόντος"),
    ("εἰμί", "present.active.participle.gen.pl.m", "ὄντων"),
    ("δίδωμι", "aorist.active.participle.acc.sg.m", "δόντα"),
    ("ποιέω", "present.active.participle.dat.pl.m", "ποιοῦσι(ν)"),
    ("σοφός", "comp.gen.sg.f", "σοφωτέρας"),
    ("σοφός", "sup.acc.pl.m", "σοφωτάτους"),
    ("μέγας", "sup.nom.sg.f", "μεγίστη"),
    ("ἀληθής", "comp.nom.pl.n", "ἀληθέστερα"),
])
def test_engine_cells(lemma, cell, form):
    e = _entry(lemma)
    assert form in cell_forms(e, cell), (cell, cell_forms(e, cell))
    assert normalize_answer(form.replace("(ν)", "ν")) in entry_forms(e)
    assert describe_cell(e, cell)


def test_irregular_comparative_has_contracted_forms():
    forms = cell_forms(_entry("μέγας"), "comp.acc.pl.m")
    assert "μείζονας" in forms and "μείζους" in forms


def test_every_verb_participle_table_declines():
    """Every participle table in the lexicon yields a full declension (30
    cells: 5 cases × 2 numbers × 3 genders, vocative included)."""
    missing = []
    for e in data.all_entries():
        if e["kind"] != "verb":
            continue
        cells = all_cells(e)
        heads = {k.rsplit(".", 1)[0] for k, _ in cells if k.count(".") == 3 and ".participle." in k and k.endswith(".m")}
        for head in heads:
            n = sum(1 for k, _ in cells if k.startswith(head + ".") and k.count(".") == 5)
            if n < 30:
                missing.append((e["lemma"], head, n))
    assert len(missing) <= 5, missing[:20]
