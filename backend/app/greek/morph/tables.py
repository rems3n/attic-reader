# Dual (Smyth §§ 195, 214, 230, 250 ff.): nominative/accusative/vocative and
# genitive/dative forms, kept in a separate "dual" block of each table so the
# learner-facing tables can hide them by default.
# ---------------------------------------------------------------------------


def _dual_cells(du: dict[str, tuple], cases=CASES, plain: bool = False) -> list[dict]:
    """du: {gender: (nom/acc/voc, gen/dat)}; plain=True for nouns (forms as a list)."""
    cells = []
    for case in cases:
        forms = {}
        for g, (nav, gd) in du.items():
            forms[g] = _l(nav if case in ("nom", "acc", "voc") else gd)
        cells.append({"case": case, "number": "du", "forms": forms[""] if plain else forms})
    return cells


