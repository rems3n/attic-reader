@pytest.mark.parametrize("word,final,long", [
    ("λο", False, False), ("γοι", True, False), ("γοις", True, True), ("χω", False, True),
    ("ται", True, False), ("ταις", True, True), ("ρᾱ", False, True), ("τῳ", True, True),
])
def test_syllable_length(word, final, long):
    assert syllable_is_long(word, final=final) is long


def test_persistent_and_recessive():
    assert persistent("ἀνθρωπου", 0) == "ἀνθρώπου"
    assert persistent("ἀνθρωποι", 0) == "ἄνθρωποι"
    assert persistent("ὀνοματος", 0) == "ὀνόματος"
    assert persistent("χωραι", 0) == "χῶραι"
    assert persistent("τιμης", 1, "circumflex") == "τιμῆς"
    assert recessive("λυομεν") == "λύομεν"
    assert recessive("ἐλυσαν") == "ἔλυσαν"
    assert recessive("λυου") == "λύου"


