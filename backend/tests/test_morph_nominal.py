@pytest.mark.parametrize("lemma,comp,sup,adv", [
    ("σοφός", "σοφώτερος", "σοφώτατος", "σοφῶς"),
    ("δίκαιος", "δικαιότερος", "δικαιότατος", "δικαίως"),
    ("μακρός", "μακρότερος", "μακρότατος", "μακρῶς"),
    ("νέος", "νεώτερος", "νεώτατος", "νέως"),
    ("ἀληθής", "ἀληθέστερος", "ἀληθέστατος", "ἀληθῶς"),
    ("ταχύς", "θάττων", "τάχιστος", "ταχέως"),
    ("ἀγαθός", "ἀμείνων", "ἄριστος", "εὖ"),
    ("κακός", "κακίων", "κάκιστος", "κακῶς"),
])
def test_comparison_and_adverb(lemma, comp, sup, adv):
    sub = {"ἀληθής": "adj-3-es", "ταχύς": "adj-us"}.get(lemma, "adj-1-2")
    t = decline(lemma, "adjective", sub, {"terminations": 3, "feminine": "x", "neuter": "x"})
    assert t["comparison"]["comparative"][0] == comp
    assert t["comparison"]["superlative"][0] == sup
    assert t["adverb"] == [adv]


