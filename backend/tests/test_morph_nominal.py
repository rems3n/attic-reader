    assert [c["forms"]["m"] for c in t["cells"]][:4] == [["ὁ"], ["τοῦ"], ["τῷ"], ["τόν"]]
    assert t["cells"][5]["forms"] == {"m": ["οἱ"], "f": ["αἱ"], "n": ["τά"]}


