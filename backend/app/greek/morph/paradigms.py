def P(id, section, title, lemma, kind, subclass, morph, explanation, examples):
    return {
        "id": id, "section": section, "title": title, "lemma": lemma, "kind": kind, "subclass": subclass,
        "morph": morph, "explanation": explanation, "examples": [{"greek": g, "english": e} for g, e in examples],
    }


def N(id, title, lemma, genitive, gender, subclass, explanation, examples, section=None):
    section = section or {"noun-1": "nouns-1", "noun-2": "nouns-2"}.get(subclass, "nouns-3")
    return P(id, section, title, lemma, "noun", subclass, {"genitive": genitive, "gender": gender}, explanation, examples)


def V(id, title, lemma, explanation, examples):
    """A verb paradigm: the forms come from the lexicon entry of `lemma`."""
    return P(id, "verbs", title, lemma, "verb", "verb", {}, explanation, examples)


def A(id, title, lemma, subclass, feminine, neuter, explanation, examples, terminations=3, kind="adjective", section="adjectives"):
    morph = {"terminations": terminations, "feminine": feminine, "neuter": neuter}
    if kind == "pronoun":
        morph = {"forms": [lemma, feminine, neuter]}
    return P(id, section, title, lemma, kind, subclass, morph, explanation, examples)


