@lru_cache(maxsize=1)
def _by_id() -> dict[str, dict]:
    return {p["id"]: p for p in PARADIGMS}


def index() -> dict:
    sections = []
    for sid, title, blurb in SECTIONS:
        items = [{"id": p["id"], "title": p["title"], "lemma": p["lemma"]} for p in PARADIGMS if p["section"] == sid]
        sections.append({"id": sid, "title": title, "blurb": blurb, "items": items})
    return {"sections": sections}


def table_for(paradigm: dict) -> dict | None:
    if paradigm["kind"] == "verb":
        from .verb import conjugate_entry  # local import: verbs come later

        return conjugate_entry(paradigm)
    return decline(paradigm["lemma"], paradigm["kind"], paradigm["subclass"], paradigm["morph"])


def get(paradigm_id: str) -> dict:
    p = _by_id()[paradigm_id]
    return {**p, "table": table_for(p)}
