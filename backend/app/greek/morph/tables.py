"""Hand-written paradigms for irregular nouns, adjectives, pronouns and numerals.

Layout: a dict keyed by lemma → {"kind", "note", "cells"} where cells is a
list of (case, number, {gender: [forms]}) for adjective-like words or
(case, number, [forms]) for nouns. Cases: nom gen dat acc voc; numbers: sg pl.
Forms are already accented; alternates are listed together.
"""

from __future__ import annotations

CASES = ("nom", "gen", "dat", "acc", "voc")


def _noun(note: str, sg: list, pl: list, gender: str) -> dict:
    cells = []
    for case, forms in zip(CASES, sg):
        cells.append({"case": case, "number": "sg", "forms": _l(forms)})
    for case, forms in zip(CASES, pl):
        cells.append({"case": case, "number": "pl", "forms": _l(forms)})
    return {"kind": "noun", "gender": gender, "note": note, "cells": cells}


def _adj(note: str, sg: list, pl: list, genders=("m", "f", "n"), kind: str = "adjective") -> dict:
    """sg/pl: five rows (nom gen dat acc voc), each a tuple of per-gender forms."""
    cells = []
    for number, rows in (("sg", sg), ("pl", pl)):
        for case, row in zip(CASES, rows):
            cells.append({"case": case, "number": number, "forms": {g: _l(f) for g, f in zip(genders, row)}})
    return {"kind": kind, "genders": list(genders), "note": note, "cells": cells}


def _l(x):
    if x is None:
        return []
    return [x] if isinstance(x, str) else list(x)


