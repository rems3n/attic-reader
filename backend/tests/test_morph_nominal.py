CASES = ("nom", "gen", "dat", "acc", "voc")


def noun(lemma, genitive, gender, subclass):
    t = decline(lemma, "noun", subclass, {"genitive": genitive, "gender": gender})
    return ["/".join(c["forms"]) for c in t["cells"]]


def adj(lemma, subclass, gender, feminine=None, neuter=None, terminations=3, kind="adjective"):
    morph = {"terminations": terminations, "feminine": feminine, "neuter": neuter}
    if kind == "pronoun":
        morph = {"forms": [lemma, feminine, neuter]}
    t = decline(lemma, kind, subclass, morph)
    return ["/".join(c["forms"][gender]) for c in t["cells"]]


